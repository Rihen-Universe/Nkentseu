		inline const char *NkI18nCode(int32 lang) {
			static const char *c[NK_I18N_LANGS] = {"fr", "en", "es", "pt", "de", "it", "ru", "gom"};
			return (lang >= 0 && lang < NK_I18N_LANGS) ? c[lang] : "en";
		}

		inline const char *const *NkI18nNames() {
			static const char *n[NK_I18N_LANGS] = {"Français", "English",  "Español", "Português",
												   "Deutsch",  "Italiano", "Русский", "Ghɔmáláʼ"};
			return n;
		}

		inline int32 &NkI18nCur() {
			static int32 c = 0;
			return c;
		}

		inline void NkI18nSet(int32 lang) {
			NkI18nCur() = (lang >= 0 && lang < NK_I18N_LANGS) ? lang : 0;
		}

