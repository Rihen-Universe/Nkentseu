		inline bool NkI18nEq(const char *a, const char *b) {
			while (*a && *a == *b) {
				++a;
				++b;
			}
			return *a == *b;
		}

		// ── Overrides EDITABLES : fichiers <code>.lang (key=value), sans recompiler ──
		struct NkI18nOv {
				NkString key, val;
				int32 lang;
		};

		inline NkVector<NkI18nOv> &NkI18nOverrides() {
			static NkVector<NkI18nOv> v;
			return v;
		}

		inline bool &NkI18nLoadedFlag() {
			static bool b = false;
			return b;
		}

		inline void NkI18nLoadFileInto(const NkString &path, int32 lang) {
			if (!NkFile::Exists(path.CStr()))
				return;
			const NkString txt = NkFile::ReadAllText(NkPath(path.CStr()));
			NkString line;
			for (const char *s = txt.CStr();; ++s) {
				if (*s == '\n' || *s == '\0') {
					const char *c = line.CStr();
					if (*c && *c != '#') {
						const char *eq = nullptr;
						for (const char *p = c; *p; ++p)
							if (*p == '=') {
								eq = p;
								break;
							}
						if (eq) {
							NkString k;
							for (const char *p = c; p < eq; ++p)
								if (*p != ' ')
									k += *p;
							const char *p = eq + 1;
							while (*p == ' ')
								++p;
							NkString val;
							for (; *p; ++p)
								val += *p;
							if (!k.Empty()) {
								NkI18nOv ov;
								ov.key = k;
								ov.val = val;
								ov.lang = lang;
								NkI18nOverrides().PushBack(ov);
							}
						}
					}
					line = NkString();
					if (*s == '\0')
						break;
				} else if (*s != '\r')
					line += *s;
			}
		}

		inline void NkI18nEnsureLoaded() {
			if (NkI18nLoadedFlag())
				return;
			NkI18nLoadedFlag() = true;
			const char *h = std::getenv("USERPROFILE");
			if (!h || !*h)
				h = std::getenv("HOME");
			const NkString home = h ? h : "";
			for (int32 l = 0; l < NK_I18N_LANGS; ++l) {
				const NkString f = NkString(NkI18nCode(l)) + ".lang";
				NkI18nLoadFileInto((NkPath("data") / "lang" / f.CStr()).ToString(), l);
				NkI18nLoadFileInto((NkPath("Applications/NKCode/data") / "lang" / f.CStr()).ToString(), l);
				if (!home.Empty())
					NkI18nLoadFileInto((NkPath(home.CStr()) / ".nkcode" / "lang" / f.CStr()).ToString(), l);
			}
		}

		inline void NkI18nReload() {
			NkI18nOverrides() = NkVector<NkI18nOv>();
			NkI18nLoadedFlag() = false;
			NkI18nEnsureLoaded();
		}

		// Traduction : override > table > anglais > cle.
		inline const char *NkT(const char *key) {
			NkI18nEnsureLoaded();
			const int32 L = NkI18nCur();
			{
				NkVector<NkI18nOv> &ov = NkI18nOverrides();
				for (usize i = 0; i < ov.Size(); ++i)
					if (ov[i].lang == L && NkI18nEq(ov[i].key.CStr(), key))
						return ov[i].val.CStr();
			}
			int32 n = 0;
			const NkTr *T = NkI18nTable(&n);
			for (int32 i = 0; i < n; ++i) {
				if (NkI18nEq(T[i].key, key)) {
					const char *v = (L >= 0 && L < NK_I18N_LANGS) ? T[i].s[L] : nullptr;
					if (v && v[0])
						return v;
					if (T[i].s[1] && T[i].s[1][0])
						return T[i].s[1];
					return key;
				}
			}
			return key;
		}

